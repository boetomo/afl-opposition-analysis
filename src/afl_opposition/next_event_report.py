"""Export portable next-event reports and a reproducible example forecast."""

import argparse
import hashlib
import json
from pathlib import Path
import shutil

import pandas as pd

from afl_opposition.next_events import NUMERIC, observed_features
from afl_opposition.next_event_model import configure, load_model, forecast_next


def export_report(root, experiment, output, *, overwrite=False):
    root, experiment, output = Path(root), Path(experiment), Path(output)
    summary = json.loads((experiment / "summary.json").read_text(encoding="utf-8"))
    if output.exists() and any(output.iterdir()) and not overwrite:
        raise ValueError("Report exists. Use --overwrite to replace this report explicitly.")
    source = root / "data/processed/2026/events.parquet"
    expected = summary["test_provenance"]["sources"]["2026"]["processed_file_sha256"]["events.parquet"]
    if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
        raise ValueError("Example source does not match the evaluated dataset.")
    model, scaler, metadata = load_model(experiment / "model")
    if metadata["fingerprint"] != summary["model_fingerprint"]:
        raise ValueError("Model does not match the reported experiment.")
    configure("cpu")
    predictions = pd.read_parquet(experiment / "test_predictions.parquet")
    events = pd.read_parquet(source)
    events = events.loc[events.possession_id.isin(predictions.possession_id)]
    # Deterministic first eligible episode, not a selected successful prediction.
    lengths = events.groupby("possession_id").possession_id.transform("size")
    episode_id = events.loc[lengths.ge(4), "possession_id"].iloc[0]
    episode = events.loc[events.possession_id.eq(episode_id)].sort_values("event_index")
    prefix = observed_features(episode.iloc[:3]).reset_index(drop=True)
    forecast = forecast_next(model, scaler, prefix)
    target = predictions.set_index("event_id").loc[prefix.iloc[-1].event_id]
    output.mkdir(parents=True, exist_ok=True)
    names = [
        "summary.json", "selection.json", "dataset_audit.json",
        "development_counts.csv", "development_coverage.csv", "test_coverage.csv",
        "example_possession.csv", "initial_search.csv", "finalists.csv", "metrics.csv",
        "per_action.csv", "test_by_team.csv",
    ]
    names += [p.name for p in experiment.glob("*-confusion.csv")]
    names += [p.name for p in experiment.glob("*-history.json")]
    for name in names:
        shutil.copyfile(experiment / name, output / name)
    columns = ["event_id", "possession_id", "event_index", "match_id", "period", "display_order",
               "team_id", "action_type", *[name for name in NUMERIC if name != "period"]]
    prefix[columns].to_csv(output / "forecast_prefix.csv", index=False)
    record = {"forecast": forecast,
              "actual_next_action": target.target_action,
              "actual_location": {"x_norm": float(target.target_x), "y_norm": float(target.target_y)}
                  if target.has_location else None,
              "selection": "First eligible 2026 episode with at least four events; predict after event three.",
              "model_fingerprint": summary["model_fingerprint"]}
    (output / "forecast_example.json").write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    (output / "README.md").write_text(
        "# Next-event example reports\n\n"
        "Generated by `python -m afl_opposition.next_event_report` from the completed "
        "`artifacts/next-event-v1` experiment. Model weights and full predictions remain "
        "local and are excluded from Git. These tables and the saved notebook outputs "
        "can be inspected without training.\n\n"
        "See [the experiment specification](../../../docs/next-event-prediction.md) "
        "and [the walkthrough](../../../notebooks/12_next_event_prediction.ipynb). "
        "2026 is an already-observed benchmark. Location errors use venue-normalised coordinates.\n",
        encoding="utf-8")
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--experiment", default="artifacts/next-event-v1")
    parser.add_argument("--output", default="reports/examples/next-event-v1")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    path = export_report(Path.cwd(), Path(args.experiment), Path(args.output), overwrite=args.overwrite)
    print("Saved report:", path.as_posix())


if __name__ == "__main__":
    main()
